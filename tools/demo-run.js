// Execution evidence: a synthetic investor taken through the whole system, with
// a report of what happened. No real data and no network by default.
//
//   node tools/demo-run.js                      writes docs/hackathon/evidence/demo-run.md and .json
//   node tools/demo-run.js --seed 5             another investor
//   OPENROUTER_API_KEY=... AI_MODEL=vendor/model node tools/demo-run.js --live
//                                               the assistant answers through the real OpenRouter API
//                                               (the same function logic, the same prompts)
//
// Steps: build the investor with planted effects -> analyse -> bias coach (rules
// judged on trades they had not seen) -> adopt a rule part-way through the
// history -> adherence -> check a buy before placing it -> ask the assistant
// five questions -> scan everything that was sent -> run the test suites.
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");
const { pathToFileURL } = require("url");
const root = path.join(__dirname, "..");
const D = require(path.join(root, "src", "decisions.js")), B = require(path.join(root, "src", "biases.js")), T = require(path.join(root, "src", "aitools.js"));
const AI = require(path.join(root, "src", "aiclient.js")), RA = require(path.join(root, "src", "rationale.js")), W = require(path.join(__dirname, "synth-world.js"));
const SH = require(path.join(root, "src", "shadow.js"));

const arg = (k, d) => { const i = process.argv.indexOf("--" + k); return i >= 0 ? process.argv[i + 1] : d; };
const live = process.argv.indexOf("--live") >= 0, seed = +arg("seed", 21);
const outBase = arg("out", path.join(root, "docs", "hackathon", "evidence", "demo-run"));
const PLANTED = { runupMean: 0.08, chase: -0.07, impulse: -0.08, impulseShare: 0.25, evening: -0.07, turbulent: -0.06, oversize: 2.2, passedEdge: 0.08, avoidEdge: -0.03, valuationEdge: 0.15 };
const pts = (x) => (x == null ? "-" : (x >= 0 ? "+" : "") + (x * 100).toFixed(1) + " pts");
const pc = (x) => (x == null ? "-" : Math.round(x * 100) + "%");
const md = [];
const line = (s) => md.push(s == null ? "" : s);

(async function () {
  const core = await import(pathToFileURL(path.join(root, "supabase", "functions", "ai-coach", "core.mjs")).href);
  if (live && (!process.env.OPENROUTER_API_KEY || !process.env.AI_MODEL)) { console.log("--live needs OPENROUTER_API_KEY and AI_MODEL."); process.exit(2); }

  const world = W.buildWorld(Object.assign({ seed, nBuys: 140, bars: 1000, nPassed: 110 }, PLANTED));
  const input = world.input, R = D.analyze(input), coach = B.coach(R);
  const tickers = Object.keys(input.tickerSymbol);
  const buys = R.decisions.filter((d) => !d.excluded && d.side === "buy").sort((a, b) => a.cut - b.cut);

  line("# Execution evidence: a synthetic investor through the whole system");
  line();
  line("Generated by `node tools/demo-run.js" + (live ? " --live" : "") + "` on " + new Date().toISOString().slice(0, 10) + ". Synthetic data only: no real person, account or trade. " +
    "The investor is built with known behaviours (below), so the report can show that the system finds what is there and recommends only what holds up on later trades.");
  line();
  line("## 1. The investor");
  line();
  line("Seed " + seed + ", " + buys.length + " analysed buys over about " + (R.coverage.monthsCovered).toFixed(0) + " months, " + input.txs.length + " records, " + Object.keys(input.prices).length + " price series.");
  line();
  line("| Planted behaviour | Setting |");
  line("|---|---|");
  [["Buys after a rise in the last 20 days before the buy (avg rise)", "+8%, each +10% costs 7 points over the next month"], ["Impulse buys (first look under an hour before)", "25% of buys, cost 8 points"], ["Buys at 21:00 or later", "cost 7 points"],
    ["Buys in turbulent markets", "cost 6 points, and 2.2x the usual size"], ["Positive calls passed on", "outperformed the market by 8 points over 3 months"], ["Negative calls on stocks not held", "lagged by 3 points"],
    ["Notes arguing from valuation (passed calls)", "+15 points over 3 months"]].forEach((r) => line("| " + r[0] + " | " + r[1] + " |"));
  line();

  line("## 2. What the bias coach found, and whether it holds up out of sample");
  line();
  line("A rule is judged by fitting it on the earlier part of the history and applying it to the later part (chronological walk-forward, with an embargo so that no trade whose outcome was still unknown is used to fit). " +
    "The gain is what following the rule would have been worth against the NASDAQ, per decision the rule flags.");
  line();
  line("| Bias | Tier | Rule | Out of sample | Flagged (later decisions) | Gain per flagged decision (99% range) | In sample (flatters) |");
  line("|---|---|---|---|---|---|---|");
  coach.biases.forEach((b) => b.rules.filter((r) => r.recommended).forEach((r) => {
    const o = r.oos;
    line("| " + b.name + " | " + b.tier + " | " + r.title + " | " + o.verdict + " | " + (o.flagged || 0) + " of " + (o.testN || 0) + " | " + (o.mean != null ? pts(o.mean) + " (" + pts(o.ci99.lo) + " to " + pts(o.ci99.hi) + ")" : "-") + " | " + (r.inSample ? pts(r.inSample.mean) : "-") + " |");
  }));
  line();
  const rejected = coach.rules.filter((r) => r.recommended && (r.oos.verdict === "unsupported" || r.oos.verdict === "unclear")).map((r) => r.title);
  line("Rules that looked good on the whole history but did not hold up out of sample, and are therefore not recommended: " + (rejected.length ? rejected.join("; ") : "none") + ".");
  line();

  // adopt the best supported rule part-way through
  const best = coach.rules.filter((r) => r.recommended && r.oos.verdict === "supported").sort((a, b) => b.oos.mean - a.oos.mean)[0];
  line("## 3. Adopting a rule, and keeping it");
  line();
  let commit = null, A = null;
  if (best) {
    const adoptedAt = buys[Math.floor(buys.length * 0.55)].cut;
    commit = B.commit(best, adoptedAt);
    A = B.adherence(commit, R, buys[buys.length - 1].cut + 864e5);
    line("The user adopts **" + best.title + "**: \"" + best.text + "\" (a click; the assistant could only propose it). Adoption is dated part-way through the history so that decisions on both sides of it exist.");
    line();
    line("- Decisions this rule covers since adoption: " + A.n + "; it was broken " + A.broken.k + " times (" + pc(A.broken.p) + "). In an equally long stretch before: " + A.before.broken.k + " of " + A.before.n + " (" + pc(A.before.broken.p) + ").");
    line("- Next month against the NASDAQ: decisions that kept the rule " + pts(A.kept.mean) + " (" + A.kept.n + "), decisions that broke it " + pts(A.broke.mean) + " (" + A.broke.n + ")" + (A.diff ? ", difference " + pts(A.diff.est) + " (95% range " + pts(A.diff.lo) + " to " + pts(A.diff.hi) + ")" : "") + ". An association, not proof.");
    const pre = B.preTrade([commit], { runup: 0.3, leadH: 2, hour: 21, pVol: 0.9, pRet: 0.9, relSize: 2.5, conviction: 0.2 });
    line("- Checking an intended buy against the adopted rule: " + (pre.hits.length ? pre.hits.map((h) => h.why.replace(/\.$/, "")).join("; ") : "no objection") + ".");
  } else line("No rule reached \"supported\" for this seed.");
  line();

  // the assistant
  line("## 4. The assistant");
  line();
  const env = { AI_PROVIDER: live ? "openrouter" : "mock", AI_ALLOWED_USERS: "demo-user", AI_MODEL: process.env.AI_MODEL || "", AI_MODEL_LITE: process.env.AI_MODEL_LITE || "" };
  let used = 0;
  const transport = async (body) => {
    const r = await core.handle({ raw: body, user: { id: "demo-user" }, env, bump: async () => ++used, callModel: async (req) => {
      const res = await fetch(core.CHAT_URLS.openrouter, { method: "POST", headers: { Authorization: "Bearer " + process.env.OPENROUTER_API_KEY, "Content-Type": "application/json" }, body: JSON.stringify(req) });
      if (!res.ok) throw Object.assign(new Error("HTTP " + res.status), { status: res.status });
      return res.json();
    } });
    return r.json;
  };
  // "now" is the end of the synthetic attention data, so the weekly review has something to show
  const now = Math.max.apply(null, input.intraday.map((e) => e.ts)) + 3600e3;
  let shadowRes = null;
  const ctx = { R, coach, commitments: commit ? [commit] : [], nameOf: (t) => t + " Corp", tickers, now, intraday: input.intraday, events: input.events, held: [], checkBuy: () => ({ facts: ["Checked against the adopted rules."], hits: [] }),
    shadow: () => shadowRes || (shadowRes = SH.run({ R, input, coach, now: input.now })) };
  line("Provider: " + (live ? "OpenRouter (live)" : "stand-in model (`AI_PROVIDER=mock`): same function, same validation, no model") + ". The agent works in steps (at most 5 requests per question): each step names more read-only tools, which run on the device, or answers. Proposed actions are cards the user must click.");
  line();
  const QUESTIONS = ["What are my biggest biases and what should I change?", "Why do my buys after a rise do worse than the others?", "Do I act on my own Positive calls?", "How well do I keep the rule I adopted?", "Is buying in the evening a problem for me?", "Review my week and remind me before I buy my most viewed stock", "Am I leaving my biases behind?", "How would the agents have done?"];
  const answers = [];
  for (const q of QUESTIONS) {
    try {
      const r = await AI.ask(q, ctx, { transport, consented: true });
      answers.push({ q, ok: true, r });
      line("**Q: " + q + "**");
      line();
      line("- " + r.steps + (r.steps === 1 ? " step" : " steps") + "; tools run on the device: " + r.results.map((x) => x.tool + (x.args && x.args.id ? "(" + x.args.id + ")" : "") + " [T0 read-only]").join(", "));
      line("- Answer: " + r.answer);
      line("- Numbers not found in the results: " + (r.unmatched.length ? r.unmatched.join(", ") : "none") + (r.actions.length ? "; proposed for the user to decide [T1, a click]: " + r.actions.map((a) => a.type.replace("_", " ") + (a.title ? " \"" + a.title + "\"" : a.stockLabel ? " for " + a.stockLabel : "")).join(", ") : ""));
      line();
    } catch (e) { answers.push({ q, ok: false, error: e.message }); line("**Q: " + q + "** - failed: " + e.message); line(); }
  }

  line("### What was sent");
  line();
  const log = AI.log(), out = log.filter((e) => e.dir === "out");
  line(out.length + " requests, " + out.reduce((s, e) => s + e.bytes, 0) + " bytes in total. Scan of every body sent:");
  line();
  const bodies = out.map((e) => e.body || "");
  const real = new RegExp("\\b(" + tickers.map((t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("|") + ")\\b");
  const checks = [["Keys naming amounts, ISINs, prices, symbols or currencies", bodies.some((b) => /"(amount|isin|price|quantity|qty|symbol|ticker|currency)"/i.test(b))],
    ["ISIN-like identifiers", bodies.some((b) => /\b[A-Z]{2}[A-Z0-9]{9}[0-9]\b/.test(b))], ["Real tickers (stocks go out as \"Stock n\")", bodies.some((b) => real.test(b.replace(/Stock \d+/g, "")))],
    ["Exact dates (dates go out by month)", bodies.some((b) => /\d{4}-\d{2}-\d{2}/.test(b))], ["Trade amounts as values", input.txs.filter((t) => t.amount >= 1000).some((t) => bodies.some((b) => b.indexOf(":" + t.amount + ",") >= 0 || b.indexOf(":" + t.amount + "}") >= 0))]];
  line("| Looked for | Found |");
  line("|---|---|");
  checks.forEach((c) => line("| " + c[0] + " | " + (c[1] ? "**YES**" : "no") + " |"));
  line();
  line("The tool log with each request's exact body is in `" + path.basename(outBase) + ".json`.");
  line();

  // the notes
  line("## 5. The notes written with calls");
  line();
  const items = RA.collect(input.events), cache = {};
  const sent = await RA.classify(items, cache, AI, { transport, consented: true });
  const st = RA.stats(R, items, cache), val = st.features.find((f) => f.key === "type:valuation");
  line(items.length + " notes, " + sent.sent + " distinct ones sent (each once, redacted), classified into kinds of reasoning. Calls whose note argued from valuation did " + pts(val.meanWith) + " over 3 months against " + pts(val.meanWithout) + " for the others" +
    (val.diff ? " (difference " + pts(val.diff.est) + ", 99% range " + pts(val.diff.lo) + " to " + pts(val.diff.hi) + (val.clear ? ", clear" : ", not clear") + ")" : "") + ". The planted edge was +15 points for the passed-on valuation calls." +
    (live ? "" : " The stand-in model classifies by keywords; the live model reads the wording."));
  line();

  // tests
  line("## 6. Test suites");
  line();
  const suites = [];
  ["test-trades.js", "test-biases.js", "test-ai.js", "test-shadow.js"].forEach((f) => {
    const r = spawnSync(process.execPath, [path.join(__dirname, f)], { encoding: "utf8", timeout: 300000 });
    const lines = (r.stdout || "").split("\n"), pass = lines.filter((l) => l.startsWith("PASS ")).length, fail = lines.filter((l) => l.startsWith("FAIL ")).length;
    suites.push({ file: f, pass, fail, exit: r.status });
  });
  line("| Suite | Passed | Failed |");
  line("|---|---|---|");
  suites.forEach((s) => line("| `node tools/" + s.file + "` | " + s.pass + " | " + s.fail + " |"));
  line();
  line("Out of sample, in worlds with no planted effect (24 worlds x 9 rules), the coach called 0 of 216 rules supported (`tools/test-biases.js`).");

  fs.mkdirSync(path.dirname(outBase), { recursive: true });
  fs.writeFileSync(outBase + ".md", md.join("\n") + "\n");
  fs.writeFileSync(outBase + ".json", JSON.stringify({ generated: new Date().toISOString(), live, seed, planted: PLANTED, suites, assistantLog: log, answers: answers.map((a) => ({ q: a.q, ok: a.ok, error: a.error, answer: a.r && a.r.answer, unmatched: a.r && a.r.unmatched, steps: a.r && a.r.steps, actions: a.r && a.r.actions.map((x) => ({ type: x.type, id: x.id, stock: x.stockLabel })), tools: a.r && a.r.results.map((x) => ({ tool: x.tool, args: x.args })) })) }, null, 1));
  console.log(md.join("\n"));
  console.log("\nWritten: " + outBase + ".md and .json");
  if (suites.some((s) => s.fail || s.exit)) process.exit(1);
})();
